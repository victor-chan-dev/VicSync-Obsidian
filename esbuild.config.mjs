import "dotenv/config";
import esbuild from "esbuild";
import process from "process";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

console.log(`esbuild version = ${esbuild.version}`);

const prod = process.argv[2] === "production";

const DEFAULT_GOOGLEDRIVE_CLIENT_ID = process.env.GOOGLEDRIVE_CLIENT_ID || "";
const DEFAULT_GOOGLEDRIVE_CLIENT_SECRET =
  process.env.GOOGLEDRIVE_CLIENT_SECRET || "";

if (
  prod &&
  (!DEFAULT_GOOGLEDRIVE_CLIENT_ID || !DEFAULT_GOOGLEDRIVE_CLIENT_SECRET)
) {
  console.error(
    "ERROR: GOOGLEDRIVE_CLIENT_ID and GOOGLEDRIVE_CLIENT_SECRET must be set for production builds!"
  );
  process.exit(1);
}

esbuild
  .context({
    banner: {
      js: banner,
    },
    loader: {
      ".svg": "text",
    },
    entryPoints: ["./src/main.ts"],
    bundle: true,
    external: [
      "obsidian",
      "electron",
      "fs",
      "tls",
      "net",
      "http",
      "https",
      "vm",
    ],
    inject: ["./esbuild.injecthelper.mjs"],
    format: "cjs",
    target: "es2022",
    alias: { "node:url": "url" },
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    minify: prod,
    outfile: "main.js",
    define: {
      "global.DEFAULT_GOOGLEDRIVE_CLIENT_ID": `"${DEFAULT_GOOGLEDRIVE_CLIENT_ID}"`,
      "global.DEFAULT_GOOGLEDRIVE_CLIENT_SECRET": `"${DEFAULT_GOOGLEDRIVE_CLIENT_SECRET}"`,
      global: "window",
      "process.env.NODE_DEBUG": `undefined`,
      "process.env.DEBUG": `undefined`,
    },
  })
  .then((context) => {
    if (process.argv.includes("--watch")) {
      context.watch();
    } else {
      context.rebuild().then(() => {
        context.dispose();
      });
    }
  })
  .catch(() => process.exit(1));
